#!/bin/bash
# pages-redirect-site.sh: build the static site that keeps old GitHub Pages
# URLs working after project sites move to another owner.
#
#   scripts/pages-redirect-site.sh <old-owner> <new-owner> <out-dir> [repo ...]
#
# Publish <out-dir> as the repo <old-owner>/<old-owner>.github.io (Pages from
# the default branch, root). It forwards <old-owner>.github.io/<repo>/<path> to
# <new-owner>.github.io/<repo>/<path> for the listed repos, keeping query and
# hash, and sends everything else to github.com/<new-owner>.
#
# With no repos listed the site forwards nothing: use that to neutralise a
# redirect site whose project sites have moved back (otherwise the old and new
# owners' sites redirect to each other in a loop).
set -eu
[ $# -ge 3 ] || { sed -n '2,14p' "$0" | sed 's/^# \{0,1\}//'; exit 2; }
OLD=$1; NEW=$2; OUT=$3; shift 3
mkdir -p "$OUT"
list=""; for r in "$@"; do list="$list\"$(printf '%s' "$r" | tr 'A-Z' 'a-z')\", "; done
list=${list%, }
page() {
  cat <<EOF
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Moved</title>
<script>
  // Project sites that moved from $OLD to $NEW.
  // Forward /<repo>/<rest> to the same path there, keeping query and hash.
  var moved = [$list];
  var parts = location.pathname.split("/");
  var repo = (parts[1] || "").toLowerCase();
  location.replace(moved.indexOf(repo) >= 0
    ? "https://$(printf '%s' "$NEW" | tr 'A-Z' 'a-z').github.io" + location.pathname + location.search + location.hash
    : "https://github.com/$NEW");
</script>
</head>
<body><p>Moved to <a href="https://github.com/$NEW">github.com/$NEW</a>.</p></body>
</html>
EOF
}
page > "$OUT/404.html"
page > "$OUT/index.html"
: > "$OUT/.nojekyll"
cat > "$OUT/README.md" <<EOF
# $OLD.github.io

Redirect site. Project sites moved from \`$OLD\` to \`$NEW\`; this forwards
\`$OLD.github.io/<repo>/...\` to \`$NEW.github.io/<repo>/...\`.

Generated by [github-repo-migration](https://github.com/crvouga/github-repo-migration)
(\`scripts/pages-redirect-site.sh\`). Forwarded repos: ${*:-none}.
EOF
echo "wrote $OUT (forwarding: ${*:-nothing})"
